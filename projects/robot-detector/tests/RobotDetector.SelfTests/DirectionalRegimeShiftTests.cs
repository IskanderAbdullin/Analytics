using System.Text.Json;
using RobotDetector.Core;

namespace RobotDetector.SelfTests;

internal static partial class Program
{
    private static MarketTrade[] DirectionalShiftTape(int bins, int firstShiftBin = -1,
        int missingBin = -1, bool includeUnknownInShiftBin = false,
        string uid = "PUBLIC-1", string session = "SESSION-A")
    {
        var start = new DateTimeOffset(2026, 11, 19, 7, 0, 0, TimeSpan.Zero);
        var trades = new List<MarketTrade>();
        for (int i = 0; i < bins; i++)
        {
            if (i == missingBin) continue;
            var at = start.AddSeconds(30 * i);
            bool after = firstShiftBin >= 0 && i >= firstShiftBin;
            foreach (var (side, lots) in new[] {
                ("BUY", after ? 90L : 50L),
                ("SELL", after ? 10L : 50L) })
            {
                trades.Add(new MarketTrade($"{uid}-{session}-{side}-{i}",
                    at, uid, "PUBLIC", "EXCHANGE", side,
                    100m, lots, "SIM-LOB", session, "SIMULATED", trades.Count));
            }
            if (includeUnknownInShiftBin && i == firstShiftBin)
                trades.Add(new MarketTrade($"{uid}-{session}-UNK-{i}",
                    at, uid, "PUBLIC", "EXCHANGE", "UNKNOWN",
                    100m, 900L, "SIM-LOB", session, "SIMULATED", trades.Count));
        }
        return trades.ToArray();
    }

    private static void DirectionShiftDetectsKnownChangeAfterPastBaseline()
    {
        var src = DirectionalShiftTape(7, firstShiftBin: 6);
        var output = DirectionalRegimeShiftResearch.Describe(From(src));
        Assert(output.InputPublicPrints == 14 && output.SourceGroups == 1 &&
               output.EvaluatedClockBins == 1 && output.UnscorableWarmupOrGapBins == 6 &&
               output.ShiftWindows.Count == 1, "one abrupt shift after six stable bins");
        var hit = output.ShiftWindows.Single();
        Assert(hit.ReferenceKnownSideLots == 600 && hit.CurrentKnownSideLots == 100 &&
               hit.CurrentTotalLots == 100 && hit.CurrentPublicPrints == 2 &&
               Math.Abs(hit.ReferenceReportedBuyShare - 0.5) < 1e-12 &&
               Math.Abs(hit.CurrentReportedBuyShare - 0.9) < 1e-12 &&
               Math.Abs(hit.SignedReportedBuyShareChange - 0.4) < 1e-12,
               "exact public history-only proportion change");
        Assert(hit.CurrentBinStartUtc.StartsWith("2026-11-19T07:03:00", StringComparison.Ordinal) &&
               hit.Direction == "reported_buy_share_increase" &&
               !hit.PhysicalOwnerIdentified && !hit.SignificanceCalibrated &&
               !output.PhysicalBotCountKnown && !output.StatisticalSignificanceEstablished,
               "does not infer a physical owner or calibrated significance");
    }

    private static void DirectionShiftStableAndMarketWideNull()
    {
        var stable = DirectionalRegimeShiftResearch.Describe(From(DirectionalShiftTape(12)));
        Assert(stable.EvaluatedClockBins == 6 && stable.CandidateShiftWindows == 0,
            "stable public mixture must not emit a change episode");

        // The same public shift can be generated by a large population
        // of unrelated actors. With no private labels it is *not* a robot.
        var aggregate = DirectionalRegimeShiftResearch.Describe(
            From(DirectionalShiftTape(7, firstShiftBin: 6)));
        Assert(aggregate.CandidateShiftWindows == 1 &&
               aggregate.ShiftWindows.All(x => !x.PhysicalOwnerIdentified),
            "public group-wide source shift confounds any owner claim");
    }

    private static void DirectionShiftGapAndUnknownSideReset()
    {
        var gap = DirectionalRegimeShiftResearch.Describe(
            From(DirectionalShiftTape(7, firstShiftBin: 6, missingBin: 3)));
        Assert(gap.ShiftWindows.Count == 0 && gap.ClockGapTransitions == 1 &&
               gap.EvaluatedClockBins == 0,
            "no time-contiguous past baseline after a missing populated clock bin");

        var incomplete = DirectionalRegimeShiftResearch.Describe(
            From(DirectionalShiftTape(8, firstShiftBin: 6,
                includeUnknownInShiftBin: true)));
        Assert(incomplete.UnscorableSideQualityBins == 1 &&
               incomplete.ShiftWindows.Count == 0,
            "unknown-dominated current bin must reset and never be called a shift");
    }

    private static void DirectionShiftAppendOnlyAndSourceIsolation()
    {
        var prefix = DirectionalRegimeShiftResearch.Describe(
            From(DirectionalShiftTape(7, firstShiftBin: 6)));
        var later = DirectionalRegimeShiftResearch.Describe(
            From(DirectionalShiftTape(14, firstShiftBin: 6)));
        Assert(prefix.ShiftWindows.Count == 1 && later.ShiftWindows.Count >= 1 &&
               prefix.ShiftWindows[0] == later.ShiftWindows[0],
            "future public prints cannot alter earlier shift observation");

        var a = DirectionalShiftTape(7, firstShiftBin: 6);
        var b = DirectionalShiftTape(7, firstShiftBin: 6,
            uid: "PUBLIC-2", session: "SESSION-B");
        var left = DirectionalRegimeShiftResearch.Describe(From(a.Concat(b).ToArray()));
        var right = DirectionalRegimeShiftResearch.Describe(From(b.Concat(a).Reverse().ToArray()));
        Assert(left.SourceGroups == 2 && left.CandidateShiftWindows == 2 &&
               JsonSerializer.Serialize(left) == JsonSerializer.Serialize(right),
            "two separate sources have no shared baselines and no input order dependence");
    }

    private static void DirectionShiftRejectsInvalidAndDense()
    {
        var rows = DirectionalShiftTape(8);
        var dense = DirectionalRegimeShiftResearch.Describe(From(rows),
            new DirectionalShiftConfig { MaximumPopulatedBinsPerGroup = 7 });
        Assert(dense.SourceGroups == 1 &&
               dense.SkippedDenseSourceGroups == 1 &&
               dense.ShiftWindows.Count == 0, "oversized source must be skipped without sampling");

        bool rejected = false;
        try { _ = DirectionalRegimeShiftResearch.Describe(
            From(rows.Append(rows[0]).ToArray())); }
        catch (InvalidDataException) { rejected = true; }
        Assert(rejected, "duplicate public event identity rejected");

        rejected = false;
        try { _ = DirectionalRegimeShiftResearch.Describe(
            From(rows), new DirectionalShiftConfig { ReferenceBins = 2 }); }
        catch (ArgumentException) { rejected = true; }
        Assert(rejected, "bad historical baseline rejected");

        rejected = false;
        try { _ = DirectionalRegimeShiftResearch.Describe(
            From(rows), new DirectionalShiftConfig { MinimumAbsoluteBuyShareChange = 0 }); }
        catch (ArgumentException) { rejected = true; }
        Assert(rejected, "invalid uncalibrated threshold rejected");
    }

    private static void DirectionShiftCooldownExplicit()
    {
        var output = DirectionalRegimeShiftResearch.Describe(
            From(DirectionalShiftTape(12, firstShiftBin: 6)),
            new DirectionalShiftConfig { CooldownBins = 100 });
        Assert(output.CandidateShiftWindows == 1,
            "one change episode with deliberately long observation cooldown");
    }
}
